// JEV decision gate: score every initiative in jev/initiatives and say
// GO / CONDITIONAL / NO-GO, with the social ROI behind each verdict.
//
//   npm run jev             print the verdict table
//   npm run jev -- --write  also regenerate docs/jev/DECISIONS.md
//   npm run jev:check       CI gate: fail when an initiative in a blocking
//                           stage (build, release, operate) is NO-GO, or when
//                           docs/jev/DECISIONS.md is out of date.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  STAGES,
  VERDICTS,
  evaluateInitiative,
  formatRatio,
} from '../src/jev/score.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const JEV_DIR = path.join(ROOT, 'jev');
const REPORT = path.join(ROOT, 'docs/jev/DECISIONS.md');

export function loadJev(root = ROOT) {
  const dir = path.join(root, 'jev');
  const config = JSON.parse(
    readFileSync(path.join(dir, 'config.json'), 'utf8'),
  );
  const initiatives = readdirSync(path.join(dir, 'initiatives'))
    .filter((name) => name.endsWith('.json'))
    .sort()
    .map((name) => {
      const parsed = JSON.parse(
        readFileSync(path.join(dir, 'initiatives', name), 'utf8'),
      );
      if (`${parsed.id}.json` !== name)
        throw new Error(`jev/initiatives/${name}: id must match the file name`);
      return parsed;
    });
  const exists = (ref) => existsSync(path.join(root, ref.split('#')[0]));
  const results = initiatives.map((initiative) =>
    evaluateInitiative(initiative, config, { exists }),
  );
  return { config, results };
}

const usd = (value) =>
  `${value < 0 ? '-' : ''}$${Math.round(Math.abs(value)).toLocaleString('en-US')}`;
const months = (value) => (value === Infinity ? 'never' : `${value} mo`);

export function renderReport({ config, results }) {
  const order = (result) => STAGES.indexOf(result.stage);
  const rows = [...results].sort(
    (a, b) => order(b) - order(a) || a.id.localeCompare(b.id),
  );
  const lines = [
    '# JEV decisions',
    '',
    '<!-- Generated by `npm run jev -- --write` from jev/. Do not edit by hand. -->',
    '',
    `Horizon ${config.horizonMonths} months, discount ${config.discountRateAnnual * 100}% a year, ` +
      `labour ${usd(config.hourlyRateUsd)}/h. SROI = present value of valued outcomes ÷ present value of costs. ` +
      `Stages ${config.ciBlockingStages.join(', ')} block CI on NO-GO. Method: [docs/JEV.md](../JEV.md).`,
    '',
    '| Initiative | Stage | Verdict | SROI | NPV | Payback | Top risk |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...rows.map(
      (r) =>
        `| ${r.title} (\`${r.id}\`) | ${r.stage} | **${r.verdict}** | ${formatRatio(r.sroi)} | ${usd(r.npvUsd)} | ${months(r.paybackMonths)} | ${r.topRisk} |`,
    ),
    '',
  ];
  for (const r of rows) {
    lines.push(`## ${r.verdict} — ${r.title}`, '');
    lines.push(
      `Stage **${r.stage}**. Costs ${usd(r.pvCostsUsd)} (present value), valued outcomes ${usd(r.pvBenefitsUsd)}.`,
      '',
    );
    if (r.reasons.length) {
      lines.push('Why:', '');
      for (const reason of r.reasons) lines.push(`- ${reason}`);
      lines.push('');
    }
    if (r.conditions.length) {
      lines.push('Conditions:', '');
      for (const condition of r.conditions) lines.push(`- ${condition}`);
      lines.push('');
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function main(argv) {
  const jev = loadJev();
  const report = renderReport(jev);
  for (const r of jev.results)
    console.log(
      `${r.verdict.padEnd(11)} ${r.stage.padEnd(9)} SROI ${formatRatio(r.sroi).padStart(7)}  ${r.id}` +
        (r.reasons.length
          ? `\n            ${r.reasons.join('\n            ')}`
          : ''),
    );
  if (argv.includes('--write')) {
    writeFileSync(REPORT, report);
    console.log(`\nWrote ${path.relative(ROOT, REPORT)}`);
  }
  if (!argv.includes('--check')) return 0;
  let failed = false;
  for (const r of jev.results) {
    if (
      jev.config.ciBlockingStages.includes(r.stage) &&
      r.verdict === VERDICTS.NO_GO
    ) {
      console.error(`JEV gate: ${r.id} is NO-GO at ${r.stage}.`);
      failed = true;
    }
  }
  const current = existsSync(REPORT) ? readFileSync(REPORT, 'utf8') : '';
  if (current !== report) {
    console.error(
      'JEV gate: docs/jev/DECISIONS.md is out of date. Run `npm run jev -- --write`.',
    );
    failed = true;
  }
  return failed ? 1 : 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  process.exitCode = main(process.argv.slice(2));
